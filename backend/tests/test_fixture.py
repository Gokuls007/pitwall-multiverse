"""Drift guard for the frontend fixture.

The frontend currently renders from `frontend/src/fixtures/race.json`,
generated by `scripts/export_fixture.py`, because Phase 5's API isn't built.
A hand-exported fixture goes stale silently the moment anything upstream is
refit — and this session's parameters moved three times. The concrete cost:
a 25% win fraction measured at `MIN_FOLLOWING_GAP_S = 0.3` was quoted in
prose after the floor had already been refitted to 0.580, i.e. the number
was wrong when it was written down.

So the fixture carries a parameter fingerprint, and this test asserts it
matches the live constants. If a refit invalidates the fixture, a test fails
instead of the UI quietly showing a number nobody re-derived. Same pattern as
`scripts/fit_noise_autocorrelation.py` and `scripts/fit_min_following_gap.py`
failing loudly on drift.

Fix on failure: re-run `python backend/scripts/export_fixture.py`.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from pitwall.simulation.lap_time import AR1_PHI
from pitwall.simulation.position import MIN_FOLLOWING_GAP_S

FIXTURES_DIR = Path(__file__).resolve().parents[2] / "frontend" / "src" / "fixtures"
FIXTURE_PATH = FIXTURES_DIR / "race.json"
RACES_DIR = FIXTURES_DIR / "races"


@pytest.fixture(scope="module")
def fixture() -> dict:
    if not FIXTURE_PATH.exists():
        pytest.skip(f"{FIXTURE_PATH} not generated; run scripts/export_fixture.py")
    return json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))


def _race_files() -> list[Path]:
    """Every generated file: per-race base files and per-driver candidate files."""
    return sorted(RACES_DIR.glob("*.json")) if RACES_DIR.exists() else []


def _driver_files() -> list[Path]:
    """Per-driver candidate files only, excluding the shared per-race base."""
    return [p for p in _race_files() if not p.name.endswith("__base.json")]


def _base_files() -> list[Path]:
    return [p for p in _race_files() if p.name.endswith("__base.json")]


@pytest.fixture(scope="module")
def live_fingerprints() -> dict[str, dict]:
    """One fresh fit per race, reused across every driver file for that race.

    Phase 6.2 produces 98 per-driver files. Fitting once per file would refit
    each race twenty times over.
    """
    from pitwall.ingestion.catalogue import get_entry
    from pitwall.ingestion.loader import load_race
    from pitwall.parameters.fit_all import (
        fit_catalogue_with_pooled_dirty_air,
        driver_params_digest,
    )

    race_keys = sorted({path.name.split("__")[0] for path in _race_files()})
    result: dict[str, dict] = {}
    for race_key in race_keys:
        entry = get_entry(race_key)
        snapshot, _ = load_race(entry.year, entry.fastf1_event_identifier)
        params = fit_catalogue_with_pooled_dirty_air([snapshot])[race_key]
        result[race_key] = {
            "minFollowingGapS": MIN_FOLLOWING_GAP_S,
            "ar1Phi": AR1_PHI,
            "pitLaneLossS": round(params.pit_lane_loss_s, 4),
            "overtakeDifficulty": round(params.overtake_difficulty, 6),
            "dirtyAirMaxPenaltyS": round(params.dirty_air.max_penalty_s, 6),
            "dirtyAirDecayScaleS": round(params.dirty_air.decay_scale_s, 6),
            "driverParamsDigest": driver_params_digest(params),
        }
    return result


# ---------------------------------------------------------------------------
# Phase 6.2: the per-driver expansion. The fingerprint guard now covers EVERY
# generated file, not one — 98 files is 98 chances for a stale number to reach
# the UI, and the whole point of the fingerprint is that staleness fails a test
# instead of shipping.
# ---------------------------------------------------------------------------


def test_every_race_file_fingerprint_matches_live_code(live_fingerprints):
    files = _race_files()
    if not files:
        pytest.skip("no per-driver fixtures; run scripts/build_fixtures.py")

    stale: list[str] = []
    for path in files:
        payload = json.loads(path.read_text(encoding="utf-8"))
        expected = live_fingerprints[payload["meta"]["raceKey"]]
        if payload["meta"]["paramFingerprint"] != expected:
            stale.append(path.name)
    assert not stale, (
        f"{len(stale)} fixture file(s) were generated under different parameters and are "
        f"stale: {stale[:5]}{'...' if len(stale) > 5 else ''}. "
        "Re-run scripts/build_fixtures.py."
    )


def test_every_driver_file_has_the_required_shape():
    files = _driver_files()
    if not files:
        pytest.skip("no per-driver fixtures; run scripts/build_fixtures.py")

    for path in files:
        payload = json.loads(path.read_text(encoding="utf-8"))
        meta, candidates = payload["meta"], payload["candidates"]
        assert meta["driver"] and meta["raceKey"], path.name
        # One file per (driver, STOP): the UI shows one stop at a time, so a
        # two-stop driver was downloading twice what was displayed.
        assert path.name == f"{meta['raceKey']}__{meta['driver']}__s{meta['stopLap']}.json"
        assert {c["originalLap"] for c in candidates} == {meta["stopLap"]}, (
            f"{path.name}: candidates for a stop this file does not name"
        )
        assert meta["realPitLaps"], f"{path.name}: eligible drivers must have a real stop"
        assert candidates, f"{path.name}: no candidates generated"

        # Now that a file is exactly one stop, at most one candidate in it can
        # reproduce reality. Still not "exactly one": a final stop with no
        # following stint cannot be shifted and the engine correctly refuses —
        # 2019 Australian RIC pitted on lap 1 for a new front wing and then
        # retired with damage on lap 29, so that second in-lap IS the retirement.
        real_marked = [c for c in candidates if c["isReal"]]
        assert len(real_marked) <= 1, f"{path.name}: {len(real_marked)} reality-reproducing candidates"
        for candidate in candidates:
            assert candidate["deltaVsSimulatedReal"], f"{path.name}: candidate has no delta trace"
            assert candidate["classification"], f"{path.name}: candidate has no distribution"


def test_no_driver_file_stores_per_seed_lap_state():
    """The storage rule that makes the payload loadable at all: summaries only.

    485,100 simulations back these files. Serialising per-seed `LapState`
    arrays would be gigabytes, and an earlier draft that stored 12 individual
    seed traces per candidate was already 71% seed data and 2-3x the size
    budget.

    Three traces per candidate *are* stored, deliberately -- a p10-p90 band
    cannot show a bimodal ensemble, so the median can sit where no seed ever
    was. This test therefore pins the shape that keeps them affordable: a hard
    cap on the count, and values aligned to the delta series rather than each
    trace repeating the lap column.
    """
    files = _race_files()
    if not files:
        pytest.skip("no per-driver fixtures; run scripts/build_fixtures.py")

    banned = {"lapStates", "seedSeries", "states"}
    for path in _driver_files():
        payload = json.loads(path.read_text(encoding="utf-8"))
        for candidate in payload["candidates"]:
            present = banned & set(candidate)
            assert not present, f"{path.name}: per-seed state stored ({present})"

            traces = candidate["seedTraces"]
            assert len(traces) <= 3, f"{path.name}: {len(traces)} seed traces stored"
            n_laps = len(candidate["deltaVsSimulatedReal"])
            for trace in traces:
                assert set(trace) == {"seed", "values"}, f"{path.name}: seed trace carries extra keys"
                assert len(trace["values"]) == n_laps, (
                    f"{path.name}: seed trace has {len(trace['values'])} values against "
                    f"{n_laps} laps -- the alignment the frontend relies on is broken"
                )
            # Same for the replay-error diagnostic.
            assert len(candidate["deltaVsActual"]) == n_laps, f"{path.name}: deltaVsActual misaligned"
            assert len(candidate["positions"]) == n_laps, f"{path.name}: positions misaligned"


def test_race_file_sizes_stay_within_the_stated_budget():
    """The spec's sizing rule, enforced rather than measured once.

    "Per-driver files should land in the low hundreds of kilobytes... if they
    come out much larger, the stored-fields list is wrong." A regression here
    should fail loudly, because the failure mode is a UI that stops loading.
    """
    files = _race_files()
    if not files:
        pytest.skip("no per-driver fixtures; run scripts/build_fixtures.py")

    # Raised from 600KB when the candidates gained a second delta series, three
    # seed trajectories and per-compound fit provenance. The number that matters
    # is the median (~300KB); this is a regression ceiling, not a target, and it
    # exists so a stored-fields mistake fails loudly instead of shipping a UI
    # that stops loading.
    oversized = [(p.name, p.stat().st_size // 1024) for p in files if p.stat().st_size > 650 * 1024]
    assert not oversized, f"files above the 600KB ceiling: {oversized}"


