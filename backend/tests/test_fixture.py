def test_a_moved_pit_stop_produces_a_non_degenerate_delta():
    """The regression guard for the bug that survived every other test here.

    The delta was originally stored as the difference of two *gap-to-leader*
    series. Gap-to-leader is floored at zero for whoever is leading, so for a
    driver who leads in both timelines the difference is identically 0.000 —
    and on the demo case (VER led laps 1-66 of Hungary 2019) it was exactly
    that on 26 of the 31 simulated laps, p10 and p90 included. Every
    fingerprint, shape, size and monotonicity assertion passed while the chart
    reported "no difference at all" for moving a pit stop by 27 laps. Only
    opening it in a browser found it.

    So: for a candidate that moves a stop by a wide margin, the post-fork delta
    must actually vary. Cumulative race time has no floor, which is why it is
    now the stored variable.
    """
    driver_files = _driver_files()
    if not driver_files:
        pytest.skip("no fixtures; run scripts/build_fixtures.py")

    checked = 0
    for path in driver_files:
        payload = json.loads(path.read_text(encoding="utf-8"))
        for candidate in payload["candidates"]:
            shift = abs(candidate["newLap"] - candidate["originalLap"])
            # Post-fork laps only; the anchor row is zero by construction.
            post_fork = [
                row for row in candidate["deltaVsSimulatedReal"] if row[0] >= candidate["divergenceLap"]
            ]
            if shift < 10 or len(post_fork) < 10:
                continue
            checked += 1
            zero_laps = sum(1 for row in post_fork if row[1] == 0.0 and row[2] == 0.0 and row[3] == 0.0)
            assert zero_laps < len(post_fork) / 2, (
                f"{path.name} lap {candidate['originalLap']}->{candidate['newLap']}: "
                f"{zero_laps} of {len(post_fork)} post-fork laps have an identically "
                "zero delta and band. The stored variable is degenerate."
            )
            # A stop moved 10+ laps must produce a visible *excursion*. The
            # first version of this asserted on the final delta instead and was
            # wrong: 2019 Australian GRO 15->25 finishes 0.26s apart, because
            # both timelines have paid the same pit loss before he retires on
            # lap 29, leaving only the tyre-pace integral. The endpoints can
            # legitimately reconverge; the excursion between them cannot vanish.
            medians = [row[1] for row in post_fork]
            assert max(medians) - min(medians) > 1.0, (
                f"{path.name} lap {candidate['originalLap']}->{candidate['newLap']}: "
                f"post-fork delta spans only {max(medians) - min(medians):.3f}s, "
                f"which a {shift}-lap change cannot plausibly produce"
            )

    assert checked > 100, f"only {checked} wide-shift candidates checked; guard is too weak"


def test_the_reality_reproducing_candidate_has_exactly_zero_decision_effect():
    """The invariant that pins the baseline.

    `deltaVsSimulatedReal` measures the alternate against an override-free fork
    at the same lap with the same seed. Phase 4's no-op test already pins that
    reference byte-for-byte against a no-op `ChangePitLap`, so for the candidate
    that reproduces reality the decision effect must be exactly 0.000 -- not
    approximately zero. Any drift here means the baseline has stopped being the
    paired reference and every candidate's delta has become uninterpretable.

    `deltaVsActual` on the same candidate is the simulator's replay error, and it
    is emphatically NOT zero (-7.4s by lap 70 on Hungary/VER). That contrast is
    the reason both series exist: differencing against actual times would put
    that 7.4s into every candidate, swamping any effect of a couple of seconds.
    """
    driver_files = _driver_files()
    if not driver_files:
        pytest.skip("no fixtures; run scripts/build_fixtures.py")

    checked = 0
    for path in driver_files:
        payload = json.loads(path.read_text(encoding="utf-8"))
        for candidate in payload["candidates"]:
            if not candidate["isReal"]:
                continue
            checked += 1
            for lap, median, low, high in candidate["deltaVsSimulatedReal"]:
                assert (median, low, high) == (0.0, 0.0, 0.0), (
                    f"{path.name} lap {lap}: reality-reproducing candidate has a "
                    f"non-zero decision effect {median}s -- the paired baseline is broken"
                )
            for trace in candidate["seedTraces"]:
                assert set(trace["values"]) == {0.0}, f"{path.name}: seed trace is non-zero"

    assert checked > 50, f"only {checked} reality-reproducing candidates found"


def test_every_implausible_answer_has_a_named_cause():
    """An answer past the plausibility bound must be attributable.

    The bound is a symptom test -- twice the fitted pit-lane loss -- and on its
    own it only says "this number is too big". Auditing what it caught turned up
    two unrelated causes it cannot distinguish:

      - 2019 Hungary VER 67->40, -52.8s, entirely pace, resting on a SOFT cell
        fitted from 2 observations with a degradation rate of exactly 0.0 s/lap
        and r2 = nan, relied on for 30 post-fork laps.
      - 2019 Hungary BOT 5->20, -108.4s, of which -86.5s is accumulated held-up
        time and only -21.9s pace, on cells that are perfectly well fitted.

    So every implausible candidate must be explained by at least one of: running
    past observed tyre age, resting on a degenerate fit, or being dominated by
    traffic rather than pace. One that is implausible with none of those is an
    unexplained engine result, and this test is where it should surface rather
    than in the UI as a confident minute of gain.
    """
    driver_files = _driver_files()
    if not driver_files:
        pytest.skip("no fixtures; run scripts/build_fixtures.py")

    unexplained, implausible, total = [], 0, 0
    for path in driver_files:
        payload = json.loads(path.read_text(encoding="utf-8"))
        for candidate in payload["candidates"]:
            total += 1
            verdict = candidate["plausibility"]
            # Every candidate carries the verdict, plausible or not.
            assert set(verdict) >= {
                "finalDeltaS",
                "implausible",
                "trafficS",
                "paceS",
                "restsOnDegenerateFit",
                "cause",
            }, f"{path.name}: incomplete plausibility verdict"
            assert "fitReliance" in candidate, f"{path.name}: no fit reliance"

            if not verdict["implausible"]:
                assert verdict["cause"] is None, f"{path.name}: plausible candidate has a cause"
                continue
            implausible += 1
            assert verdict["cause"] in {
                "degenerateFit",
                "traffic",
                "extrapolation",
                "unexplained",
            }, f"{path.name}: unknown cause {verdict['cause']!r}"
            if verdict["cause"] == "unexplained":
                unexplained.append(
                    f"{path.name} {candidate['originalLap']}->{candidate['newLap']}: "
                    f"{verdict['finalDeltaS']}s ({verdict['sPerLap']}s/lap)"
                )

    assert implausible > 0, "no implausible candidates at all -- is the bound wired up?"

    # Unexplained is a permitted verdict, not a passing grade, and it currently
    # never fires: the taxonomy accounts for all 2,419 implausible candidates
    # (extrapolation 1,971, traffic 314, degenerate fit 134).
    #
    # It did fire before the degradation fallback chain was fixed -- 2021 Spanish
    # HAM 28->12 and PER 57->44, both ~+58s with well-fitted cells and inside
    # observed tyre age. Correcting the chain changed the fitted pit-lane loss
    # (it is measured against expected clean pace, which depends on the tyre
    # models), which moved the bound, and both fell inside it. So the residual
    # was downstream of a real parameter bug rather than a genuine third cause.
    # The guard stays because the next one might not be.
    share = len(unexplained) / max(1, total)
    # Tightened from 0.005 to just above the observed 0.00025 (2 of 8,085). A cap
    # with 20x headroom is not a regression guard, it is a rubber stamp — the same
    # shape of mistake as the fallback-fraction ceiling that sat at 40% while the
    # race that mattered was at 19%.
    assert share < 0.001, (
        f"{len(unexplained)} of {total} candidates ({share:.2%}) are implausible with no "
        "identified cause, which is too many to wave through: " + "; ".join(unexplained[:10])
    )


def test_every_driver_file_carries_its_per_driver_constants_once():
    """The per-driver constants live in `meta`, not on all ~140 candidates.

    `tyreCells` (observation count, r2, slope, cliff per compound) and the
    plausibility bound are identical across every candidate a driver has.
    Repeating them measured 7.5% of the payload for no information. Each candidate
    keeps only `fitReliance` — how many post-fork laps *that* candidate runs on
    each compound — which is the part that actually varies.

    Asserted because the join is now the frontend's job, and a candidate naming a
    compound absent from `meta.tyreCells` would silently lose its caveat.
    """
    files = _driver_files()
    if not files:
        pytest.skip("no per-driver fixtures; run scripts/build_fixtures.py")

    for path in files:
        payload = json.loads(path.read_text(encoding="utf-8"))
        meta = payload["meta"]
        assert meta["tyreCells"], f"{path.name}: no tyre cells in meta"
        assert meta["plausibilityBoundS"] > 0, f"{path.name}: no plausibility bound"
        known = {cell["compound"] for cell in meta["tyreCells"]}
        for candidate in payload["candidates"]:
            assert "tyreCells" not in candidate, f"{path.name}: cells still repeated per candidate"
            assert "boundS" not in candidate["plausibility"], f"{path.name}: bound still repeated"
            unknown = set(candidate["fitReliance"]) - known
            assert not unknown, f"{path.name}: reliance on compounds missing from meta: {unknown}"


def test_stored_per_lap_positions_are_present_and_ordered():
    """Phase 6.4 reads the order at a lap; it never interpolates one.

    That only works if position is stored per lap on both sides. The spec claimed
    6.4 "needs no new data" because per-lap positions exist for every seed — true
    of the engine's `LapState`, but the precompute never stored them, so they had
    to be added. This asserts both halves are there and are sane.
    """
    driver_files, base_files = _driver_files(), _base_files()
    if not driver_files:
        pytest.skip("no per-driver fixtures; run scripts/build_fixtures.py")

    for path in base_files:
        payload = json.loads(path.read_text(encoding="utf-8"))
        positions = payload["realPositions"]
        assert len(positions) >= 15, f"{path.name}: only {len(positions)} drivers have positions"
        for code, series in positions.items():
            laps = [lap for lap, _ in series]
            assert laps == sorted(laps), f"{path.name} {code}: laps out of order"
            for _, position in series:
                assert 1 <= position <= 26, f"{path.name} {code}: position {position}"

    for path in driver_files:
        payload = json.loads(path.read_text(encoding="utf-8"))
        for candidate in payload["candidates"]:
            for entry in candidate["positions"]:
                if entry is None:
                    continue
                median, best, worst = entry
                assert 1 <= best <= median <= worst <= 26, (
                    f"{path.name}: position spread {entry} is not ordered best<=median<=worst"
                )
